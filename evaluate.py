"""
Compare embedding strategies and the two grouping methods on a corpus.

    python evaluate.py                                   # bundled 100 docs
    python evaluate.py --docs data/sample_1000.jsonl     # larger random sample
    python evaluate.py --configs minilm-truncated minilm-chunked

Writes reports/<corpus>.json and reports/<corpus>.md. See evaluation.py for
what each metric measures.
"""

import argparse
import json
import logging
import time
from dataclasses import replace
from pathlib import Path
from typing import Any, Dict, List

from config import Settings
from data_loader import Embedder, load_docs, load_or_embed
from evaluation import (
    compare_partitions,
    npmi_coherence,
    self_retrieval,
    threshold_sweep,
    topic_diversity,
    topic_stability,
)
from similarity import SimilarityGraph
from topic_modeling import run_topic_modeling

CONFIGS = {
    "minilm-truncated": ("all-MiniLM-L6-v2", "truncated"),  # original behaviour
    "minilm-chunked": ("all-MiniLM-L6-v2", "chunked"),
    "bge-small-chunked": ("BAAI/bge-small-en-v1.5", "chunked"),
    "mpnet-chunked": ("all-mpnet-base-v2", "chunked"),
}


def evaluate_config(name: str, docs: List[Dict[str, Any]], settings: Settings) -> Dict[str, Any]:
    model_name, strategy = CONFIGS[name]
    embedder = Embedder(model_name, strategy, settings.chunk_overlap)
    texts = [d["text"] for d in docs]
    syllabi = [d.get("syllabus") or "" for d in docs]

    start = time.time()
    doc_emb, chunks = load_or_embed(embedder, texts, settings.cache_dir)
    embed_seconds = time.time() - start
    # Syllabi are queries, so embed them the same way as the documents.
    query_emb, _ = load_or_embed(Embedder(model_name, strategy, settings.chunk_overlap), [s or " " for s in syllabi], settings.cache_dir)

    topic_ids, topics, outlier_fraction = run_topic_modeling(docs, doc_emb, settings.random_state)
    topic_terms = [t["top_terms"] for t in topics.values()]

    doc_ids = [str(d["id"]) for d in docs]
    graph = SimilarityGraph(
        doc_ids, doc_emb, threshold=settings.sim_threshold, percentile=settings.sim_percentile, knn=settings.sim_knn
    )
    comparison = compare_partitions(doc_ids, topic_ids, graph.community_labels())
    stats = graph.get_sim_stats()

    return {
        "config": name,
        "model": model_name,
        "strategy": strategy,
        "chunks": int(len(chunks.doc_idx)),
        "embed_seconds": round(embed_seconds, 1),
        "self_retrieval": self_retrieval(doc_emb, query_emb, [bool(s) for s in syllabi]),
        "pairwise_similarity": {k: round(stats[k], 4) for k in ("mean", "p90", "p95")},
        "topics": {
            "count": len(topics),
            "outlier_fraction": round(outlier_fraction, 3),
            "npmi": round(npmi_coherence(topic_terms, texts), 4),
            "diversity": round(topic_diversity(topic_terms), 4),
            "stability_ari": round(topic_stability(docs, doc_emb), 4),
            "labels": {str(k): v["summary"] for k, v in topics.items()},
            "sizes": {str(k): v["size"] for k, v in topics.items()},
        },
        "graph": {
            "knn": graph.knn,
            "threshold": round(graph.threshold, 4),
            "communities": len(graph.communities),
            "modularity": round(graph.modularity(), 4),
        },
        "agreement": {k: round(comparison[k], 4) for k in ("ari", "nmi", "disagreement_rate")},
        "threshold_sweep": threshold_sweep(doc_ids, doc_emb, topic_ids),
    }


def render_markdown(corpus: str, num_docs: int, results: List[Dict[str, Any]]) -> str:
    lines = [
        f"# Evaluation: `{corpus}` ({num_docs} documents)",
        "",
        "Generated by `evaluate.py`. Metric definitions are in `evaluation.py`.",
        "",
        "## Embedding strategies",
        "",
        "Self-retrieval: each case's syllabus is used as a query against all opinions; "
        "a good opinion embedding ranks the case's own opinion first.",
        "",
        "| Config | Chunks | MRR | R@1 | R@5 | Median rank | Mean pair sim | Embed time (s) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        sr = r["self_retrieval"]
        lines.append(
            f"| {r['config']} | {r['chunks']} | {sr['mrr']:.3f} | {sr['recall_at_1']:.3f} | "
            f"{sr['recall_at_5']:.3f} | {sr['median_rank']:.0f} | {r['pairwise_similarity']['mean']:.3f} | "
            f"{r['embed_seconds']} |"
        )
    lines += [
        "",
        "## Topics and agreement",
        "",
        "| Config | Topics | Outliers (pre-reassign) | NPMI | Diversity | Seed stability (ARI) | "
        "Communities | Modularity | ARI topics↔communities | NMI | Disagreement |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in results:
        t, g, a = r["topics"], r["graph"], r["agreement"]
        lines.append(
            f"| {r['config']} | {t['count']} | {t['outlier_fraction']:.0%} | {t['npmi']:.3f} | "
            f"{t['diversity']:.2f} | {t['stability_ari']:.3f} | {g['communities']} | {g['modularity']:.3f} | "
            f"{a['ari']:.3f} | {a['nmi']:.3f} | {a['disagreement_rate']:.0%} |"
        )
    for r in results:
        lines += [
            "",
            f"## Threshold sweep: {r['config']}",
            "",
            "| k-NN | Percentile | Threshold | Edges | Isolated docs | Communities | Largest share | Modularity | ARI vs topics | NMI vs topics |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for row in r["threshold_sweep"]:
            lines.append(
                f"| {row['knn']} | p{row['percentile']} | {row['threshold']:.3f} | {row['edges']} | {row['isolated_docs']} | "
                f"{row['communities']} | {row['largest_community_share']:.0%} | {row['modularity']:.3f} | "
                f"{row['ari_vs_topics']:.3f} | {row['nmi_vs_topics']:.3f} |"
            )
        lines += ["", "Topics: " + "; ".join(
            f"{k}: {v} ({r['topics']['sizes'][k]})" for k, v in r["topics"]["labels"].items()
        )]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--docs", type=Path, default=Settings().docs_path)
    parser.add_argument("--configs", nargs="+", default=list(CONFIGS), choices=list(CONFIGS))
    parser.add_argument("--out", type=Path, default=Path("reports"))
    args = parser.parse_args()

    logging.basicConfig(level=logging.WARNING)
    settings = replace(Settings(), docs_path=args.docs)
    docs = load_docs(args.docs)
    results = []
    for name in args.configs:
        print(f"Evaluating {name}...")
        results.append(evaluate_config(name, docs, settings))

    args.out.mkdir(parents=True, exist_ok=True)
    stem = args.docs.stem
    (args.out / f"{stem}.json").write_text(json.dumps(results, indent=2))
    (args.out / f"{stem}.md").write_text(render_markdown(args.docs.name, len(docs), results))
    print(f"Wrote {args.out / stem}.md and .json")


if __name__ == "__main__":
    main()
